#!/usr/bin/env python3
"""
ADDED FOR THIS SAMPLE
Generate VERIFICATION.md — commands only.

VERIFICATION.md is a PUBLIC file: it must never contain PASS/FAIL claims or
references to local-only raw logs. This generator therefore emits only the
commands a reviewer can run to reproduce verification, plus the pinned
provenance commit. Gate outcomes stay in local raw logs and are never
written here.

If raw gate logs exist and any gate FAILED, the script still exits non-zero
(it reports to stdout only) so CI can catch a bad state without the public
file ever claiming a result.

Usage: python3 tools/generate_verification.py
"""
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RAW = REPO / '_internal' / 'release' / 'raw'


def any_gate_failed():
    """True if any raw gate log records a FAIL. Missing logs -> False."""
    if not RAW.is_dir():
        return False
    for log in RAW.glob('*.log'):
        text = log.read_text(errors='replace')
        if re.search(r'GATE \S+: FAIL|RELEASE CHECK: FAIL', text):
            return True
    return False


def main():
    prov = json.loads((REPO / 'PROVENANCE.json').read_text())
    commit = prov['origin']['commit']
    n_extracts = sum(len(sd['extracts']) for sd in prov['samples'].values())

    lines = [
        '# NEXO Samples — Verification',
        '',
        'This file lists the commands used to verify this repository. It is',
        'GENERATED by `tools/generate_verification.py` — do not edit by hand.',
        'It intentionally contains no pass/fail claims: run the commands',
        'below and inspect the output yourself.',
        '',
        '## Commands',
        '',
        '```bash',
        'make deps-check          # required tools present (non-zero if missing)',
        'make up && make down     # user-space PG+PgBouncer+Redis lifecycle',
        'make test-01 .. test-06  # per-sample demos (env must be up)',
        'bash tools/negative_tests.sh      # sabotage controls (env must be up)',
        'make verify-fast         # php -l + docs lint + shellcheck',
        'make verify ORIGIN=...   # full release gate suite',
        '```',
        '',
        'Each command exits non-zero on failure; a skipped test is not a pass.',
        '',
        f'Provenance: {n_extracts} extracts pinned to ORIGIN commit '
        f'`{commit}` (see PROVENANCE.json / PROVENANCE.md). Verify with:',
        '',
        '```bash',
        'python3 tools/provenance/verify.py /path/to/origin/repo',
        'python3 tools/mutation_tests.py /path/to/origin/repo',
        'python3 tools/independent_recheck.py /path/to/origin/repo',
        '```',
        '',
        '## Notes',
        '',
        '- Simulated components are labeled SIMULATED in code and READMEs.',
        '- Sample 04 contains functional Spanish (LLM prompts/regexes),',
        '  allowlisted in `tools/lang_allowlist.txt`.',
        '- `tools/negative_tests.sh` proves each harness assertion detects a',
        '  deliberately broken dependency (RLS off, dropped function, Redis',
        '  down) and restores the environment afterwards.',
        '',
    ]
    out = '\n'.join(lines)
    (REPO / 'VERIFICATION.md').write_text(out)
    print('VERIFICATION.md generated (commands only, no gate claims)')
    if any_gate_failed():
        print('WARNING: local raw gate logs contain FAIL entries — '
              'the public file intentionally does not report them.')
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
